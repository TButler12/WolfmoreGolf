-- Club Event Phase 2: best-ball + field skins schema additions
--
-- Backward compat notes (confirmed by code audit, 2026-11-22):
--   • tournament_hole_scores is NOT touched by the live app (3.2.x).
--     The existing app uses the separate `hole_scores` table for Wolf/Stableford.
--   • Existing RLS policies on tournament_hole_scores are kept intact.
--     New group-scorer policies are added alongside them.
--   • points kept NOT NULL DEFAULT 0 (conservative; no live-app decoding to break).
--
-- Scoring model: store gross only; net computed at read time via BestBallEngine.rawStrokes.
-- Lock model: tournament_events.status = 'finished' blocks group-scorer writes.
-- Auth model:
--   • Group scorer: sends x-group-code header (6-char code the scorer entered).
--   • Organizer: sends x-device-id header as before.
--   • Spectators / leaderboard: existing public SELECT policy, no headers needed.
--
-- RUN ORDER: local → staging → production.
-- Validate both the current App Store build and the club-events build before prod.

-- ─────────────────────────────────────────
-- 1. tournament_rules — best-ball / skins settings
-- ─────────────────────────────────────────

alter table tournament_rules
  add column handicap_allowance   float    not null default 1.0,
  add column gross_leaderboard    boolean  not null default false,
  add column gross_skins_enabled  boolean  not null default true,
  add column net_skins_enabled    boolean  not null default true,
  add column skins_carryover      boolean  not null default false,
  add column entry_fee_per_player numeric,
  add column team_places_paid     int      not null default 3;

-- ─────────────────────────────────────────
-- 2. tournament_players — group assignment
-- ─────────────────────────────────────────
-- group_code: 6 chars; uppercase; no 0, 1, O, I (easy to misread).
-- Generated by the scoring device at group setup; organizer can pre-assign.
-- Uniqueness per event is enforced by the app when generating codes.
-- starting_hole: shotgun start position (1–18).

alter table tournament_players
  add column group_code    text check (
                             group_code ~ '^[2-9A-HJ-NP-Z]{6}$'
                           ),
  add column starting_hole smallint not null default 1
                           check (starting_hole between 1 and 18);

create index on tournament_players (group_code);

-- ─────────────────────────────────────────
-- 3. tournament_hole_scores — gross score + audit column
-- ─────────────────────────────────────────
-- gross_score: the raw strokes taken; net computed on read.
-- points kept NOT NULL DEFAULT 0 for backward compat (no live-app decoding to break,
-- but keeping the constraint avoids any surprise if old code ever hits this table).
-- updated_at: set on every UPDATE so score edits are traceable.

alter table tournament_hole_scores
  add column gross_score int,
  add column updated_at  timestamptz not null default now();

create or replace function trgfn_set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end $$;

create trigger trg_hole_scores_updated_at
  before update on tournament_hole_scores
  for each row execute function trgfn_set_updated_at();

-- ─────────────────────────────────────────
-- 4. Unique constraint on (player, day, hole)
--    — duplicate-row guard first
-- ─────────────────────────────────────────
-- The live app never inserts into tournament_hole_scores, so no existing duplicates
-- are expected. The DO block will abort with a count if any exist.

do $$
declare
  dup_count int;
begin
  select count(*) into dup_count
  from (
    select tournament_player_id, day, hole_number
    from   tournament_hole_scores
    group  by tournament_player_id, day, hole_number
    having count(*) > 1
  ) dupes;

  if dup_count > 0 then
    raise exception
      'Found % duplicate (player, day, hole) combination(s) in tournament_hole_scores — '
      'resolve before adding unique constraint', dup_count;
  end if;
end $$;

alter table tournament_hole_scores
  add constraint uq_hole_score_player_day_hole
  unique (tournament_player_id, day, hole_number);

-- ─────────────────────────────────────────
-- 5. RLS — add group-scorer policies alongside existing ones
-- ─────────────────────────────────────────
-- Existing policies kept intact:
--   "public read tournament_hole_scores"   → SELECT open to everyone (leaderboard + Realtime)
--   "player submit own score"              → old per-player INSERT (kept for compat)
--   "organizer manage tournament_hole_scores" → old organizer ALL (kept; recreated below
--                                              is redundant but replacing avoids drift)
--
-- New policies:
--   "group scorer insert score"  → INSERT when x-group-code matches the player's group
--   "group scorer update score"  → UPDATE same condition
--   Both blocked once status = 'finished'.
--   No DELETE for group scorer — only organizer can delete.

-- Group scorer — INSERT
-- Blocked after event is finished.
create policy "group scorer insert score"
  on tournament_hole_scores for insert
  with check (
    exists (
      select 1
      from   tournament_players tp
      join   tournament_events  e  on e.id = tp.tournament_id
      where  tp.id = tournament_player_id
        and  tp.group_code = nullif(
               current_setting('request.headers', true)::jsonb->>'x-group-code', ''
             )
        and  e.status <> 'finished'
    )
  );

-- Group scorer — UPDATE
create policy "group scorer update score"
  on tournament_hole_scores for update
  using (
    exists (
      select 1
      from   tournament_players tp
      join   tournament_events  e  on e.id = tp.tournament_id
      where  tp.id = tournament_player_id
        and  tp.group_code = nullif(
               current_setting('request.headers', true)::jsonb->>'x-group-code', ''
             )
        and  e.status <> 'finished'
    )
  );

-- Note: no "group scorer delete" — scorers may only INSERT/UPDATE.
